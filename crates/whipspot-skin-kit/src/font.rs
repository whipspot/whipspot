/// The font image (16 cells across) and the font over it, whose sprites point at `image`. Glyph
/// pixels are `colour` with alpha 255, the rest alpha 0; a character the font lacks draws `?`.
pub fn pixel_font(colour: Rgb, image: ImageId) -> (SkinImage, BitmapFont) {
    let (w, h) = (COLUMNS * CELL_W, ROWS * CELL_H);
    let mut rgba = vec![0u8; w as usize * h as usize * 4];
    let mut glyphs = Vec::with_capacity(GLYPHS);
    for (i, rows) in TABLE.iter().enumerate() {
        let (cx, cy) = (i as u32 % COLUMNS * CELL_W, i as u32 / COLUMNS * CELL_H);
        for (dy, row) in rows.iter().enumerate() {
            for dx in 0..5u32 {
                if row >> (4 - dx) & 1 == 1 {
                    let at = ((cy + dy as u32) * w + cx + dx) as usize * 4;
                    rgba[at..at + 4].copy_from_slice(&[colour.r, colour.g, colour.b, 255]);
                }
            }
        }
        glyphs.push((
            char::from(FIRST + i as u8),
            SpriteRect {
                image,
                rect: Rect {
                    x: cx,
                    y: cy,
                    w: CELL_W,
                    h: CELL_H,
                },
            },
        ));
    }
    let font = BitmapFont {
        cell: Size {
            w: CELL_W,
            h: CELL_H,
        },
        glyphs,
        fallback: Some('?'),
    };
    // Both sides are small constants, so the image is always valid; an empty fallback image
    // would be a bug, not an input error.
    let img = SkinImage::new(w, h, rgba).unwrap_or_else(|| {
        SkinImage::new(1, 1, vec![0; 4]).expect("a 1 x 1 image is always valid")
    });
    (img, font)
}

#[cfg(test)]
mod tests {
    use super::*;
    use whipspot_core::skin::MAX_GLYPHS;

    fn font() -> (SkinImage, BitmapFont) {
        pixel_font(Rgb { r: 9, g: 8, b: 7 }, ImageId(3))
    }

    #[test]
    fn ninety_five_glyphs_with_a_fallback_inside_the_image() {
        let (img, font) = font();
        assert_eq!(font.glyphs.len(), 95);
        assert!(font.glyphs.len() <= MAX_GLYPHS);
        assert_eq!(font.fallback, Some('?'));
        assert!(font.glyphs.iter().any(|(c, _)| *c == '?'));
        assert_eq!(font.glyphs[0].0, ' ');
        assert_eq!(font.glyphs[94].0, '~');
        for (_, s) in &font.glyphs {
            assert_eq!(s.image, ImageId(3));
            assert_eq!((s.rect.w, s.rect.h), (font.cell.w, font.cell.h));
            assert!(s.rect.x + s.rect.w <= img.width());
            assert!(s.rect.y + s.rect.h <= img.height());
        }
    }

    #[test]
    fn glyph_pixels_are_the_colour_and_the_rest_is_clear() {
        let (img, font) = font();
        let lit = |c: char| -> usize {
            let s = font.glyphs.iter().find(|(g, _)| *g == c).unwrap().1.rect;
            let mut n = 0;
            for y in s.y..s.y + s.h {
                for x in s.x..s.x + s.w {
                    let at = (y * img.width() + x) as usize * 4;
                    let p = &img.rgba()[at..at + 4];
                    if p[3] == 255 {
                        assert_eq!(&p[..3], &[9, 8, 7]);
                        n += 1;
                    } else {
                        assert_eq!(p[3], 0);
                    }
                }
            }
            n
        };
        assert_eq!(lit(' '), 0);
        assert_eq!(lit('.'), 4);
        assert_eq!(lit('-'), 5);
        assert!(lit('A') > 10);
    }

    #[test]
    fn every_glyph_but_space_has_pixels_and_the_table_has_no_repeats() {
        for (i, rows) in TABLE.iter().enumerate() {
            assert!(rows.iter().all(|r| *r < 0x20), "glyph {i}");
            assert_eq!(rows.iter().all(|r| *r == 0), i == 0, "glyph {i}");
            for (j, other) in TABLE.iter().enumerate().skip(i + 1) {
                assert_ne!(rows, other, "glyphs {i} and {j} are the same");
            }
        }
    }
}
