//! A built-in pixel font for skins that bring no bitmap font of their own: printable ASCII in a
//! 5 x 7 glyph in a 6 x 8 cell, drawn in one colour. The glyph table below is our own, written
//! in code (hard rule 4).

use whipspot_core::skin::{BitmapFont, ImageId, Rect, Rgb, Size, SkinImage, SpriteRect};

/// First and last character of the font.
const FIRST: u8 = 0x20;
const LAST: u8 = 0x7e;
const GLYPHS: usize = (LAST - FIRST) as usize + 1;
/// The size of one glyph cell.
